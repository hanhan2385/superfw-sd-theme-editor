# -*- coding: utf-8 -*-
"""Generate app/assets.py for the desktop editor (fonts, icons, strings)."""
import base64, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "ref", "superfw", "res")

EN = dict(re.findall(r'"(MSG_[A-Z0-9_]+)"\s*:\s*"([^"]*)"',
                     open(os.path.join(RES, "messages.py"), encoding="utf-8").read()))
ZH = json.load(open(os.path.join(RES, "lang", "zh.json"), encoding="utf-8"))

KEYS = ["MSG_UIS_THEME","MSG_UIS_LANG","MSG_UIS_RECNT","MSG_UIS_ANSPD","MSG_UIS_BHID",
        "MSG_UIS_SAVE","MSG_KNOB_ENABLED","MSG_KNOB_DISABLED","MSG_UIS_SPD2",
        "MSG_GBALOAD_MINFO","MSG_LOADINFO_GAME","MSG_LOADINFO_SAVE","MSG_LOAD_GBA",
        "MSG_GBALOAD_MPATCH","MSG_DEFS_PATCH","MSG_LOADER_SAVET","MSG_LOADER_MENU",
        "MSG_LOADER_RTCE","MSG_PATCH_TYPE3","MSG_TOOLS0_SDRAM","MSG_TOOLS1_SRAM",
        "MSG_TOOLS2_BAT","MSG_TOOLS3_BENCH","MSG_TOOLS4_FBAK","MSG_SAVETYPE_EEPROM",
        "MSG_LANG_NAME","MSG_LOADER_ST0","MSG_PATCH_TYPE_I3"]
STR = {k: {"en": EN.get(k, ""), "zh": ZH.get(k) or EN.get(k, "")} for k in KEYS}

def load_hex(path):
    out = {}
    for line in open(path, encoding="utf-8", errors="ignore"):
        line = line.strip()
        if ":" not in line:
            continue
        cp_s, data = line.split(":", 1)
        try:
            out[int(cp_s, 16)] = data.lower()
        except ValueError:
            pass
    return out

ascii_g = load_hex(os.path.join(RES, "fonts", "unscii-16.hex"))
full_g = load_hex(os.path.join(RES, "fonts", "unscii-16-full.hex"))

need = set(range(32, 127))
for pair in STR.values():
    for lang in ("en", "zh"):
        for ch in pair[lang]:
            if ord(ch) > 127:
                need.add(ord(ch))
for lit in ["清除闪存", "补丁:", "加载 GBA ROM"]:
    for ch in lit:
        need.add(ord(ch))

glyphs = {}
for cp in sorted(need):
    if cp in ascii_g:
        glyphs[cp] = bytes.fromhex(ascii_g[cp])
    elif cp in full_g:
        glyphs[cp] = bytes.fromhex(full_g[cp])

def b64(p):
    return base64.b64encode(open(p, "rb").read()).decode()

src = f'''# -*- coding: utf-8 -*-
"""Auto-generated by tools/build_app_assets.py — do not edit."""

# codepoint -> raw 1bpp rows (16 rows of 8px, or 16 rows of 16px for CJK)
FONT = {{
'''
for cp, data in glyphs.items():
    src += f"    {cp}: {data!r},\n"
src += "}\n\n"
icons_png = os.path.join(ROOT, "dist", "icons", "icons.png")
if not os.path.exists(icons_png):
    icons_png = os.path.join(RES, "icons.png")
src += f'ICONS_PNG = "{b64(icons_png)}"\n'
src += f'LOGO_PNG = "{b64(os.path.join(RES, "logo.png"))}"\n'
src += "STRINGS = " + json.dumps(STR, ensure_ascii=False) + "\n"

open(os.path.join(ROOT, "app", "assets.py"), "w", encoding="utf-8").write(src)
print("glyphs", len(glyphs), "size", len(src))
