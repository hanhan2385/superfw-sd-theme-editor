# -*- coding: utf-8 -*-
"""
从 ref/superfw/src/res/icons.h 生成 app/fwassets.py（图标锚点 + 调色板）。

固件里的图标块是 4352 字节的索引数据，注入/定位都需要"原件长什么样"。
把它内嵌进 app，这样打包成 exe 之后不依赖 ref/ 目录。
"""
import base64
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ref", "superfw", "src", "res", "icons.h")
OUT = os.path.join(ROOT, "app", "fwassets.py")


def parse(path):
    text = open(path, encoding="utf-8").read()
    body = text[text.index("icons_img"):text.index("icons_pal")]
    rows = []
    for m in re.finditer(r"\{([^{}]*)\}", body):
        r = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1))]
        if len(r) == 8:
            rows.append(bytes(r))
    pal = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{4})", text[text.index("icons_pal"):])]
    names = re.findall(r"ICON_([A-Z0-9_]+),", text[:text.index("icons_img")])
    return b"".join(rows), pal, names


def main():
    data, pal, names = parse(SRC)
    b64 = base64.b64encode(data).decode()
    chunk = "\n".join('    "%s"' % b64[i:i + 96] for i in range(0, len(b64), 96))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# -*- coding: utf-8 -*-\n")
        f.write('"""Auto-generated by tools/build_fwassets.py - do not edit."""\n')
        f.write("import base64\n\n")
        f.write("# 原始图标块（17 个 16x16，每个 4 个 8x8 tile，索引 0 = 透明）\n")
        f.write("ICONS_IMG = base64.b64decode(\n%s\n)\n\n" % chunk)
        f.write("ICONS_IMG_LEN = %d\n" % len(data))
        f.write("ICONS_IMG_HEAD = ICONS_IMG[:64]\n")
        f.write("ICONS_IMG_TAIL = ICONS_IMG[-64:]\n\n")
        f.write("ICONS_PAL = [\n")
        for i in range(0, len(pal), 8):
            f.write("    " + ", ".join("0x%04x" % v for v in pal[i:i + 8]) + ",\n")
        f.write("]\n\n")
        f.write("ICON_ORDER = %r\n" % (names,))
    print("图标块 %d 字节，调色板 %d 色，枚举 %d 个 -> %s" % (len(data), len(pal), len(names), OUT))


if __name__ == "__main__":
    sys.exit(main())
